# 给定一个链表的头节点  head ，返回链表开始入环的第一个节点。 如果链表无环，则返回 null。

# 如果链表中有某个节点，可以通过连续跟踪 next 指针再次到达，则链表中存在环。 
# 为了表示给定链表中的环，评测系统内部使用整数 pos 来表示链表尾连接到链表中的位置（索引从 0 开始）。
# 如果 pos 是 -1，则在该链表中没有环。注意：pos 不作为参数进行传递，仅仅是为了标识链表的实际情况。

# 不允许修改 链表。
 
# 思路：
# 遍历节点，一个节点出现两次就说明有环，第一次出现的节点就是入环的第一个节点。用哈希表
def detectCycle(head):
    visited = set()
    # 这行真的向内存申请了一块 8 个槽的哈希表。
    # 存进去的是"节点对象"，不是节点的值。

    while head is not None:
        # 【原代码 while head:】判断的是 bool(head)，靠默认真值侥幸能跑；
        # 一旦节点类定义 __bool__/__len__，条件就变成对内容做判断。

        if head in visited:
            # in 触发哈希表查找，内部三步：
            #   1) 算 hash(head)（普通对象默认由内存地址算出）
            #   2) 用 hash 定位槽位
            #   3) 槽里有东西，再确认是不是同一个节点
            # 代价 O(1)，与集合里已有多少元素无关。
            #
            # 命中 = 第二次到达 = 绕回来了 = 它就是入环点。
            # 是 return（交还调用方），不是 print（打印到屏幕）。
            return head

        visited.add(head)
        # 必须先查后加。反过来的话，第一个节点立刻被判成重复。
        head = head.next
    return None
