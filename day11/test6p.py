# 1、先厘清两种形式
# 形式A：把匿名函数赋值给变量
# f = lambda x: x+1
# # 本质：给匿名函数绑定一个标识符，后续可以反复调用 f()
# 形式B：直接临时传入、用完即扔
# sorted(lst, key=lambda x: x[0])
# # 匿名函数只在这里用一次，执行结束就销毁，不留名字
# 你疑惑的点：f=lambda 看着像“给不用命名的东西强行起名”，什么时候有意义？
# 场景1：需要多次复用这个逻辑
# # 提取分数的规则要在多处调用：排序、过滤、取值
# get_score = lambda t: t[1]

# res1 = sorted(L, key=get_score)
# res2 = list(filter(lambda t: get_score(t)>80, L))
# 如果每次都手写一遍 lambda t:t[1]，代码重复冗余；赋值变量后一处定义、多处复用，和普通def命名函数作用一致，只是写法轻量化。

# 场景2：作为回调、参数配置里的固定逻辑
# 部分框架需要提前传入一个可调用对象，必须有变量承接，没法现场临时写。

# 场景3：闭包、动态生成函数后保存引用
# def make_add(n):
#     return lambda x:x+n

# add5 = make_add(5)
# add10 = make_add(10)
# # 必须用变量接住生成的匿名函数，不然函数直接丢失无法调用
# 2、lambda 赋值变量 vs def 定义普通函数 的取舍
# 小逻辑（一行就能写完） lambda 一行搞定，不用缩进、换行，写起来轻便；
# get_name = lambda t:t[0]
# # 对比def
# def get_name(t):
#     return t[0]
# 功能上100%等价，只是语法简洁度差异。

# 复杂逻辑（分支、循环、多行代码） lambda天生只能写单行表达式，这种情况只能用def，lambda做不到。
# 3、回到你最开始的疑惑：为什么不在sorted里直接写lambda，还要单独写def函数？
# 题目里单独写by_name、by_score两个命名函数，是教学目的：

# 新手理解key是接收一个函数对象，分步拆解逻辑；
# 实际工程里两种写法都合理：
# 一次性排序：直接内嵌lambda最简：
# L2 = sorted(L, key=lambda t:t[0])
# 排序逻辑后续还要复用：抽成命名函数（def或者赋值lambda都行）。
# 4、真正“脱裤子放屁”的无效写法
# # 纯多余：先赋值变量，紧接着只用一次
# f = lambda t:t[0]
# sorted(L, key=f)
# 这种情况完全没必要，直接写key=lambda t:t[0]即可，你直觉反感的其实是这种无意义赋值； 只有当后续还要反复使用这个函数时，赋值才有价值。

# 精简总结
# 一次性临时使用：直接内嵌lambda，不要赋值变量；
# 需要多次复用逻辑：赋值变量保存匿名函数，合理省事；
# 多行复杂逻辑：必须用def定义命名函数，lambda无力支撑；
# 单纯为了传一次参数还专门赋值变量，确实没必要，属于冗余写法。
